import { rolldown } from 'rolldown';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root=fileURLToPath(new URL('../',import.meta.url));
const bundle=await rolldown({input:resolve(root,'server/automation/entry.ts'),platform:'neutral',treeshake:true,
  resolve:{mainFields:['module','main'],conditionNames:['deno','browser','import','default']},
  onwarn(warning,defaultHandler){if(warning.code==='UNRESOLVED_IMPORT')throw new Error(warning.message);defaultHandler(warning);}});
const output=resolve(root,'supabase/functions/automation-worker/index.ts');
await bundle.write({file:output,format:'es',minify:true});
await bundle.close();
// Prepended after writing: minify drops rolldown's banner option, and the marker must survive.
const banner='// Generated by npm run build:automation. Source: server/automation. Do not edit or commit. No credentials are embedded.\n';
const code=readFileSync(output,'utf8');
if(!code.startsWith(banner))writeFileSync(output,banner+code);
