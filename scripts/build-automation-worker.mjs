import { rolldown } from 'rolldown';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root=fileURLToPath(new URL('../',import.meta.url));
const bundle=await rolldown({input:resolve(root,'server/automation/entry.ts'),platform:'neutral',treeshake:true,
  resolve:{mainFields:['module','main'],conditionNames:['deno','browser','import','default']},
  onwarn(warning,defaultHandler){if(warning.code==='UNRESOLVED_IMPORT')throw new Error(warning.message);defaultHandler(warning);}});
await bundle.write({file:resolve(root,'supabase/functions/automation-worker/index.ts'),format:'es',minify:true,
  banner:'// Generated by npm run build:automation. Source: server/automation. No credentials are embedded.'});
await bundle.close();
