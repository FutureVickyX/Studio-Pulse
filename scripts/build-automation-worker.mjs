import { rolldown } from 'rolldown';
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

// Default: one self-contained, minified file for `supabase functions deploy`.
// `--connector`: a readable file for deploying through the Supabase connector, which takes the source
// inline. supabase-js and zod (and any subpath of them) stay as `npm:` imports pinned to the exact
// installed versions, which the Edge runtime resolves at deploy time, so only this project's own code
// is in the file. Every import form (named, side-effect, re-export, dynamic) is pinned through
// rolldown's `paths`, and the build fails if the output imports anything else.
const connector=process.argv.includes('--connector');
const root=fileURLToPath(new URL('../',import.meta.url));
const packages=['@supabase/supabase-js','zod'];
const owner=id=>packages.find(name=>id===name||id.startsWith(`${name}/`));
const versions={};
if(connector){
  const require=createRequire(resolve(root,'package.json'));
  for(const name of packages)versions[name]=require(`${name}/package.json`).version;
}
const pin=id=>{const name=owner(id);return name?`npm:${name}@${versions[name]}${id.slice(name.length)}`:id;};
const bundle=await rolldown({input:resolve(root,'server/automation/entry.ts'),platform:'neutral',treeshake:true,
  external:connector?id=>owner(id)!==undefined:[],
  resolve:{mainFields:['module','main'],conditionNames:['deno','browser','import','default']},
  onwarn(warning,defaultHandler){if(warning.code==='UNRESOLVED_IMPORT')throw new Error(warning.message);defaultHandler(warning);}});
// Generated in memory, checked, then written once: a failed check never leaves a half-made file to deploy.
const {output}=await bundle.generate(connector?{format:'es',minify:false,comments:false,paths:pin}:{format:'es',minify:true});
await bundle.close();
const [chunk]=output;
if(output.length!==1||chunk.type!=='chunk')throw new Error(`Expected one output file, got ${output.length}`);
if(connector){
  // `imports` lists each external as written after `paths`, so every entry must already be `npm:`.
  const unpinned=[...chunk.imports,...chunk.dynamicImports].filter(id=>!id.startsWith('npm:'));
  if(unpinned.length)throw new Error(`Unpinned import left in the connector build: ${unpinned.join(', ')}`);
}
// Prepended here: minify drops rolldown's banner option, and the marker must survive.
const banner=`// Generated by npm run build:automation${connector?' -- --connector':''}. Source: server/automation. Do not edit or commit. No credentials are embedded.\n`;
writeFileSync(resolve(root,'supabase/functions/automation-worker/index.ts'),chunk.code.startsWith(banner)?chunk.code:banner+chunk.code);
